#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""tools/export_isaac.py - generate biped_Laika/isaac_values.py, the robot config as plain Python values for Isaac Lab.

  python tools/export_isaac.py

Run it again after every change to biped_Laika/biped_Laika.yaml, so that an Isaac Lab environment uses the
same numbers as the MuJoCo tools and the real robot. The generated file contains only plain Python lists and
dicts (it does not depend on an Isaac Lab version); its comments say which Isaac Lab setting each value is
meant for. tools/contract_check.py --onehot checks the generated values against the deploy path.
"""
import os

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = yaml.safe_load(open(os.path.join(ROOT, "biped_Laika/biped_Laika.yaml")))


def _standing_base_height():
    """Base height of the MJCF's `standing` keyframe, read from the model so that the two cannot drift apart."""
    import mujoco
    m = mujoco.MjModel.from_xml_path(os.path.join(ROOT, "biped_Laika", "biped_Laika.xml"))
    k = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_KEY, "standing")
    assert k >= 0, "the MJCF has no `standing` keyframe"
    return float(m.key_qpos[k][2])


def _total_mass():
    """Total mass of the robot (kg), also read from the MJCF: the single source for training constants that scale with body weight."""
    import mujoco
    m = mujoco.MjModel.from_xml_path(os.path.join(ROOT, "biped_Laika", "biped_Laika.xml"))
    return float(m.body_mass.sum())

joints = cfg["joints"]
by_model = {}
for j in joints:
    by_model.setdefault(j["motor"], []).append(j["name"])

lines = []
w = lines.append
w('# Generated by tools/export_isaac.py from biped_Laika/biped_Laika.yaml. Do not edit: change the yaml and regenerate.')
w('')
w(f'JOINT_ORDER = {[j["name"] for j in joints]!r}')
w('')
w('# URDF joint limits. The Isaac action term must clamp its targets to them (as policy_io.action_to_target does).')
w(f'JOINT_LIMITS = {({j["name"]: tuple(j["range"]) for j in joints})!r}')
w('')
w(f'DEFAULT_JOINT_POS = {cfg["standing_pose"]!r}')
w('')
w('# One entry per motor model, with the joints that use it. effort_limit is the torque limit written to the motor\n'
  '# firmware, not the rated torque. armature / friction are the values identified on the real actuators.\n'
  '# each -> ImplicitActuatorCfg(joint_names_expr, stiffness, damping,')
w('#                             effort_limit_sim, velocity_limit_sim)')
prof = cfg["gain_profiles"]["rl_default"]
act = {m: {"joint_names": by_model[m],
           "stiffness": prof[m][0], "damping": prof[m][1],
           # tau_limit (the value actually written to the motor firmware), not tau_max (the rated torque):
           # a policy trained against the rated torque would count on torque the real robot does not deliver.
           "effort_limit": (cfg.get("tau_limit") or cfg["tau_max"])[m],
           "velocity_limit": cfg["vel_limit"][m],
           # Identified on the real actuators (armature on the bare motor, friction with the motor installed).
           # On the Isaac side they go to the armature / friction parameters of ImplicitActuatorCfg.
           "armature": (cfg.get("armature") or {}).get(m, 0.0),
           "friction": (cfg.get("joint_friction") or {}).get(m, 0.0),
           "joint_damping": cfg.get("joint_damping", 0.0)} for m in by_model}
w(f'ACTUATORS = {act!r}')
w('')
w('# All gain profiles (gain_profiles in biped_Laika/biped_Laika.yaml). A policy profile can select one other than')
w('# rl_default with its gain_profile key; the environment config then overrides the stiffness / damping of the\n'
  '# actuators. ACTUATORS always holds rl_default.')
# joint_overrides (per-joint [kp, kd]) is kept as a dict: list(dict) would silently turn it into a list of keys
w(f'GAIN_PROFILES = {({k: {m: ({j: list(g) for j, g in v.items()} if m == "joint_overrides" else list(v)) for m, v in d.items()} for k, d in cfg["gain_profiles"].items()})!r}')
w('')
w(f'ACTION_SCALE = {cfg["policy"]["action_scale"]!r}')
w(f'ACTION_CLIP = {cfg["policy"]["action_clip"]!r}')
w(f'CONTROL_RATE_HZ = {cfg["policy"]["control_rate_hz"]!r}   # sim dt * decimation must give exactly this rate')
w('')
w('# Observation terms in concatenation order, with their scales. Identical to what tools/sim2sim.py feeds the\n'
  '# policy: do not add, remove or reorder terms.')
w(f'OBS_SPEC = {cfg["policy"]["obs"]!r}')
w('')
w(f'DOMAIN_RAND = {cfg["domain_rand"]!r}')
w('')
w('# Initial state: base height of the "standing" keyframe and total mass. Both are read from the MJCF')
w('# (biped_Laika/biped_Laika.xml) when this file is generated, never hard-coded.')
w(f'INIT_BASE_HEIGHT = {_standing_base_height():.4f}')
w(f'TOTAL_MASS_KG = {_total_mass():.3f}')
w('')
w('# Policy profile overrides (policy_profiles in biped_Laika/biped_Laika.yaml): a profile brings its own nominal_pose /')
w('# action_scale / init_base_height, which replace the defaults above. OBS_SPEC is the base observation (45 values);')
w('# a profile can append terms to it with obs_extra (the walk profile appends gait_phase).')
w(f'POLICY_PROFILES = {(cfg.get("policy_profiles") or {})!r}')
w('')
w('# Body pairs whose meshes overlap at the zero pose (excluded from contact in the MJCF). In Isaac Lab prefer')
w('# self_collisions=False; if self-collision is enabled, these pairs must be excluded there as well.')
w("CONTACT_EXCLUDE_PAIRS = [('base_link', 'l_hip_pitch_link'),"
  " ('base_link', 'r_hip_pitch_link'),"
  " ('l_calf_link', 'l_ankle_roll_link'), ('r_calf_link', 'r_ankle_roll_link')]")
w('')

out = os.path.join(ROOT, "biped_Laika", "isaac_values.py")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(lines) + "\n")
print(f"generated {out}")

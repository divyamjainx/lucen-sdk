#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""tools/build_arm_model.py - generate the working MuJoCo scene of an arm from its config and its source MJCF.

The source MJCF of an arm (model.mjcf in the config) is the plain model: its joint damping and friction are
generic defaults, it has no armature, its actuator force range is not the torque limit the motors are deployed
with, and it has no end-effector site, contact exclusions or keyframes. This tool fills all of that in from the
config and writes the scene (model.scene in the config) that the bridge, tools/fake_bridge.py and the arm tools
load. Do not edit the scene by hand: change the config and run this tool again.

  python tools/build_arm_model.py --config humanoid_arm/humanoid_arm.yaml   # humanoid_arm/mjcf/humanoid_arm.xml -> humanoid_arm_scene.xml
  python tools/build_arm_model.py --config Arm/Arm.yaml                     # Arm/mjcf/arm.xml -> arm_scene.xml
  python tools/build_arm_model.py --config Arm/Arm_pair.yaml                # leader + follower (model.instances) -> arm_pair_scene.xml
  python tools/build_arm_model.py --config Arm/Arm.yaml --check             # verify only: exit code 1 if scene and config differ

Written for every joint, according to its motor model in the config:
  damping = joint_damping      frictionloss = joint_friction[motor]      armature = armature[motor]
  actuatorfrcrange = ±tau_limit[motor]   (the simulation clips at the same torque limit as the real motors)
  range: taken from the MJCF. A different range in the config is an error: the bridge clamps to the config range, so
  the two must agree.
Added: <site name=ee> (end_effector in the config; a list for two arms), <contact><exclude> for every parent-child
pair of bodies and for the pairs under model.contact_exclude (excludes of the source file are kept), and the
keyframes home and ready from home_pose / ready_pose.
Removed: the <actuator> section of the source file. Torque is computed by the bridge / fake bridge from the MIT
command frame; position actuators in the model would fight it.
Bodies listed under model.no_collision_bodies get no collision geometry.
A gripper joint is processed if the MJCF contains it. Joints of the MJCF that have no motor (the gripper fingers)
are listed under model.passive_joints.
"""
import argparse
import copy
import os
import sys
import xml.etree.ElementTree as ET

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = ("GENERATED by tools/build_arm_model.py from {cfg} + {src} — do not hand-edit; "
          "rerun the tool after changing {cfg}")


def instantiate(root, instances):
    """Place several copies of the single-arm source in one scene (model.instances in the config: [{prefix, pos}]).
    In each copy every body, joint, named geom and site gets the prefix and the root body is moved to pos; the contact
    excludes and equality constraints of the source are copied for each instance. Mesh assets are shared."""
    world = root.find("worldbody")
    robots = world.findall("body")
    excludes = [(e.get("body1"), e.get("body2")) for c in root.findall("contact") for e in c.findall("exclude")]
    eqs = [e for q in root.findall("equality") for e in q]
    for tag in ("contact", "equality"):
        for old in root.findall(tag):
            root.remove(old)
    for b in robots:
        world.remove(b)
    contact, equality = ET.SubElement(root, "contact"), ET.SubElement(root, "equality")
    for inst in instances:
        pre, pos = inst["prefix"], [float(v) for v in inst.get("pos", (0, 0, 0))]
        for b in robots:
            c = copy.deepcopy(b)
            for el in c.iter():
                if el.get("name"):
                    el.set("name", pre + el.get("name"))
            base = [float(v) for v in (c.get("pos") or "0 0 0").split()]
            c.set("pos", " ".join(fmt(a + d) for a, d in zip(base, pos)))
            world.append(c)
        for b1, b2 in excludes:
            ET.SubElement(contact, "exclude", body1=pre + b1, body2=pre + b2)
        for e in eqs:
            c = copy.deepcopy(e)
            for k in ("name", "joint1", "joint2"):
                if c.get(k):
                    c.set(k, pre + c.get(k))
            equality.append(c)


def load(cfg_path):
    cfg = yaml.safe_load(open(cfg_path))
    src = os.path.join(ROOT, cfg["model"]["mjcf"])
    tree = ET.parse(src)
    if cfg["model"].get("instances"):
        instantiate(tree.getroot(), cfg["model"]["instances"])
    return cfg, src, tree


def joint_params(cfg, in_mjcf=None):
    """-> {joint_name: {damping, frictionloss, armature, frc, range, motor}} for the joints present in the MJCF.
    A gripper is included only if the MJCF has that joint (in_mjcf = set of MJCF joint names; None = skip every gripper)."""
    out = {}
    for j in cfg["joints"]:
        if j.get("kind") == "gripper" and (in_mjcf is None or j["name"] not in in_mjcf):
            continue
        m = j["motor"]
        out[j["name"]] = dict(
            motor=m,
            damping=float(cfg["joint_damping"]),
            frictionloss=float(cfg["joint_friction"][m]),
            armature=float(cfg["armature"][m]),
            frc=float(cfg["tau_limit"][m]),
            range=[float(j["range"][0]), float(j["range"][1])],
        )
    return out


def fmt(x):
    s = f"{x:.6g}"
    return s


def build(cfg, src, tree, cfg_name=""):
    root = tree.getroot()
    body_of = {}                      # joint -> body element
    parent_of = {}                    # body name -> parent body name
    for parent in root.iter("body"):
        for child in parent.findall("body"):
            parent_of[child.get("name")] = parent.get("name")
    for body in root.iter("body"):
        for jt in body.findall("joint"):
            body_of[jt.get("name")] = body
    params = joint_params(cfg, set(body_of))
    passive = set((cfg.get("model") or {}).get("passive_joints") or [])

    missing = sorted(set(params) - set(body_of))
    if missing:
        raise SystemExit(f"joints {missing} of {cfg_name} are not in {os.path.basename(src)}")
    extra = sorted(set(body_of) - set(params) - passive)
    if extra:
        raise SystemExit(f"joints {extra} of {os.path.basename(src)} are not in {cfg_name} "
                         f"(every MJCF joint needs a motor; list passive joints under model.passive_joints)")

    # ---- per-joint parameters ----
    for name, p in params.items():
        jt = body_of[name].find(f"joint[@name='{name}']")
        lo, hi = (float(v) for v in jt.get("range").split())
        if abs(lo - p["range"][0]) > 1e-4 or abs(hi - p["range"][1]) > 1e-4:
            raise SystemExit(f"{name}: {cfg_name} range {p['range']} != MJCF range [{lo}, {hi}] "
                             f"(copy the range from the MJCF into the yaml, not the other way round)")
        jt.set("damping", fmt(p["damping"]))
        jt.set("frictionloss", fmt(p["frictionloss"]))
        jt.set("armature", fmt(p["armature"]))
        jt.set("actuatorfrcrange", f"-{fmt(p['frc'])} {fmt(p['frc'])}")

    # ---- simplified collision meshes (optional: used when meshes_collision/<mesh>.stl exists) ----
    col_dir = os.path.join(os.path.dirname(src), "meshes_collision")
    asset = root.find("asset")
    swapped = []
    for body in root.iter("body"):
        geoms = body.findall("geom")
        for g in geoms:
            if g.get("type") != "mesh" or g.get("contype") == "0":
                continue                                   # visual geoms (contype=0) are left alone
            mesh = g.get("mesh")
            col = os.path.join(col_dir, f"{mesh}.stl")
            if os.path.exists(col):
                col_name = f"{mesh}_col"
                if asset.find(f"mesh[@name='{col_name}']") is None:
                    ET.SubElement(asset, "mesh", name=col_name, content_type="model/stl",
                                  file=f"../meshes_collision/{mesh}.stl", scale="0.001 0.001 0.001")
                g.set("mesh", col_name)
                swapped.append(mesh)

    # ---- bodies without collision (model.no_collision_bodies): those whose convex hull would enclose other links ----
    for name in (cfg.get("model") or {}).get("no_collision_bodies") or []:
        body = next(b for b in root.iter("body") if b.get("name") == name)
        for g in body.findall("geom"):
            if g.get("class") != "visual" and g.get("contype") != "0":
                g.set("contype", "0")
                g.set("conaffinity", "0")

    # ---- actuators of the source file: removed (see the module docstring) ----
    for old in root.findall("actuator"):
        root.remove(old)

    # ---- end-effector site (a dict for one arm, a list for two) ----
    ees = cfg.get("end_effector") or []
    for ee in ([ees] if isinstance(ees, dict) else ees):
        link = next(b for b in root.iter("body") if b.get("name") == ee["link"])
        for old in link.findall(f"site[@name='{ee.get('site', 'ee')}']"):
            link.remove(old)
        ET.SubElement(link, "site", name=ee.get("site", "ee"),
                      pos=" ".join(fmt(v) for v in ee["site_pos"]),
                      size="0.01", rgba="1 0.2 0.2 0.8", group="2")

    # ---- contact exclude: parent-child pairs (bracket and motor housing interpenetrate at a joint by design) ----
    kept = [(e.get("body1"), e.get("body2")) for c in root.findall("contact") for e in c.findall("exclude")]
    for old in root.findall("contact"):
        root.remove(old)
    contact = ET.SubElement(root, "contact")
    seen = set()

    def exclude(b1, b2):
        if frozenset((b1, b2)) not in seen:
            seen.add(frozenset((b1, b2)))
            ET.SubElement(contact, "exclude", body1=b1, body2=b2)

    for child, parent in parent_of.items():
        exclude(parent, child)
    for b1, b2 in (cfg.get("model") or {}).get("contact_exclude") or []:   # non-adjacent pairs with spurious contact (listed in the yaml)
        exclude(b1, b2)
    for b1, b2 in kept:                                                    # excludes carried by the source file
        exclude(b1, b2)

    # ---- keyframe home ----
    for old in root.findall("keyframe"):
        root.remove(old)
    order = [jt.get("name") for body in root.iter("body") for jt in body.findall("joint")]
    kf = ET.SubElement(root, "keyframe")
    for key in ("home_pose", "ready_pose"):
        pose = cfg.get(key)
        if pose:
            ET.SubElement(kf, "key", name=key.replace("_pose", ""),
                          qpos=" ".join(fmt(float(pose.get(n, 0.0))) for n in order))

    root.insert(0, ET.Comment(HEADER.format(cfg=cfg_name, src=os.path.basename(src))))
    return params, swapped


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True, metavar="YAML",
                    help="humanoid_arm/humanoid_arm.yaml | Arm/Arm.yaml | Arm/Arm_pair.yaml")
    ap.add_argument("--check", action="store_true", help="only verify that the generated scene matches the config; write nothing")
    args = ap.parse_args()
    cfg, src, tree = load(args.config)
    cfg_name = os.path.basename(args.config)
    out = os.path.join(ROOT, cfg["model"]["scene"])
    params, swapped = build(cfg, src, tree, cfg_name)
    ET.indent(tree, space="  ")
    xml = ET.tostring(tree.getroot(), encoding="unicode")
    if args.check:
        cur = open(out).read() if os.path.exists(out) else ""
        if cur.strip() != xml.strip():
            print(f"[check] {os.path.relpath(out, ROOT)} is out of sync with {cfg_name} -> rerun tools/build_arm_model.py"
                  + ("" if cfg_name == "" else f" --config {cfg_name}"))
            sys.exit(1)
        print(f"[check] {os.path.relpath(out, ROOT)} is in sync with {cfg_name} ✓")
        return
    open(out, "w").write(xml + "\n")
    print(f"[build] {os.path.relpath(out, ROOT)} <- {os.path.relpath(src, ROOT)} + {os.path.basename(args.config)}")
    for n, p in params.items():
        print(f"  {n:<13} {p['motor']}  damping={p['damping']} frictionloss={p['frictionloss']} "
              f"armature={p['armature']} frc=±{p['frc']}")
    print(f"  collision meshes: {'simplified ' + str(swapped) if swapped else 'original (no meshes_collision/ directory)'}")
    try:
        import mujoco
        m = mujoco.MjModel.from_xml_path(out)
        d = mujoco.MjData(m)
        mass = sum(m.body_mass[1:])
        print(f"  MuJoCo {mujoco.__version__} loads the scene ✓  total mass {mass:.4f} kg")
        for k in range(m.nkey):
            mujoco.mj_resetDataKeyframe(m, d, k)
            mujoco.mj_forward(m, d)
            pairs = sorted({tuple(sorted((m.body(m.geom_bodyid[c.geom1]).name,
                                          m.body(m.geom_bodyid[c.geom2]).name)))
                            for c in d.contact[:d.ncon]})
            tg = " ".join(f"{v:+.1f}" for v in d.qfrc_bias)
            print(f"  keyframe {m.key(k).name:<6} contact pairs: {str(pairs or 'none'):<24} gravity torque τg=[{tg}] N·m")
            if pairs:
                print(f"  !! contact remains in this pose: either a real collision, or a pair to add under "
                      f"model.contact_exclude in {cfg_name}")
    except ImportError:
        print("  (mujoco is not installed here: load check skipped)")


if __name__ == "__main__":
    main()

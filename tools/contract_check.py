#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""tools/contract_check.py - checks of the biped policy I/O contract that need no trained policy.

Run them before training, and again after any change to biped_Laika/biped_Laika.yaml.

A. --onehot: send a ±0.1 one-hot action on each joint and derive the joint target through three independent
   code paths, which must agree (a difference > 1e-9 is a FAIL):
     chain 1  policy_io.action_to_target        - the path shared by sim2sim and the real-robot deploy tool
     chain 2  biped_Laika/isaac_values.py       - the values generated by tools/export_isaac.py, recomputed
              the way an Isaac Lab action term does (clip -> * scale -> + nominal -> clamp to the joint limits)
     chain 3  bridge round trip to_motor -> to_sim - sign / offset / nearest-turn handling must not alter
              the target (also when the raw motor angle is off by whole turns, raw_now ± 2πk)
   Every policy profile in biped_Laika/biped_Laika.yaml is covered. The last lines print a digest: run the
   command on each machine you use (training workstation, robot computer, ...). Identical digests mean the
   joint-target math is bit-identical on all of them.

B. --onehot-mujoco: feed the one-hot targets to the MuJoCo model (base fixed, gravity off) and check that
   physically the right joint moves, in the commanded direction, and settles on the target. This catches a
   flipped axis or a wrong joint mapping in the model, which the math chains cannot see. The same physical
   check on the Isaac side is up to your training environment.

C. --replay DUMP.npz --policy X.onnx: replay observation frames recorded on the robot (written by
   tools/deploy_policy.py --dump-frames) through the same ONNX on this machine and compare the outputs
   element by element with the ones computed on the robot computer. Expected: bit-identical on the same
   machine; across CPU architectures (different NEON / AVX kernels) |Δ| ≤ 1e-6 is accepted and the number
   of bit-identical frames is reported.

Usage:
  python tools/contract_check.py --onehot                         # once on each machine, then compare the digests
  python tools/contract_check.py --onehot-mujoco
  # on the robot computer:  python tools/deploy_policy.py --policy X.onnx --dump-frames 50 --dump-path d.npz ...
  python tools/contract_check.py --replay d.npz --policy X.onnx   # on your computer

Every check prints a PASS / FAIL line. The run ends with ALL PASS (exit code 0) or FAILED (exit code 1).
"""
import argparse
import hashlib
import importlib.util
import os
import sys

import numpy as np
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

FAIL = []


def check(name, cond, detail=""):
    print(f"  {'PASS' if cond else 'FAIL'}  {name}  {detail}")
    if not cond:
        FAIL.append(name)


def _isaac_values():
    spec = importlib.util.spec_from_file_location(
        "isaac_values", os.path.join(ROOT, "biped_Laika", "isaac_values.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def isaac_target(V, profile, a):
    """Chain 2: recompute the joint target from isaac_values alone, the way an Isaac Lab action term has to
    (clip ±ACTION_CLIP -> * scale -> + nominal -> clamp to [joint limits ∩ target_bounds])."""
    prof = (V.POLICY_PROFILES.get(profile) or {}) if profile else {}
    nominal = prof.get("nominal_pose") or V.DEFAULT_JOINT_POS
    scale = prof.get("action_scale", V.ACTION_SCALE)
    asj = prof.get("action_scale_joint") or {}
    tb = prof.get("target_bounds") or {}
    clip_a = V.ACTION_CLIP
    out = []
    for i, n in enumerate(V.JOINT_ORDER):
        ai = min(max(float(a[i]), -clip_a), clip_a)
        lo, hi = V.JOINT_LIMITS[n]
        if n in tb:
            lo, hi = max(lo, tb[n][0]), min(hi, tb[n][1])
        out.append(min(max(nominal[n] + asj.get(n, scale) * ai, lo), hi))
    return np.array(out)


def _wrap_pi(a):
    """Copy of bridge.wrap_pi (the bridge is not imported here: it pulls in python-can, which is only needed on the robot computer)."""
    return (a + np.pi) % (2 * np.pi) - np.pi


def bridge_roundtrip(rows, name, q, raw_now):
    """Chain 3: the math of the bridge's to_motor / to_sim, with sign / offset read from
    biped_Laika/biped_Laika.yaml (the same source as the bridge's joint map). A target sent on the nearest
    turn must read back unchanged."""
    sign, off = rows[name]
    raw_ref = raw_now + _wrap_pi(sign * q + off - raw_now)       # to_motor
    return sign * _wrap_pi(raw_ref - off)                        # to_sim


def run_onehot():
    from tools.policy_io import PolicyIO
    cfg = yaml.safe_load(open(os.path.join(ROOT, "biped_Laika/biped_Laika.yaml")))
    rows = {j["name"]: (j["sign"], j["offset"]) for j in cfg["joints"]}
    V = _isaac_values()
    profiles = [None] + sorted(cfg.get("policy_profiles") or {})
    digest = hashlib.sha256()
    for prof in profiles:
        io = PolicyIO(cfg, prof)
        tag = prof or "(default)"
        check(f"{tag}: joint order is the same", list(io.names) == list(V.JOINT_ORDER))
        nominal = io.default
        worst = 0.0
        moved_ok = clamp_note = True
        for i in range(12):
            for s in (+0.1, -0.1):
                a = np.zeros(12)
                a[i] = s
                t1 = io.action_to_target(a, cmd=np.zeros(3), phase=0.0)   # chain 1 (zero command -> zero feed-forward)
                t2 = isaac_target(V, prof, a)                      # chain 2
                worst = max(worst, float(np.abs(t1 - t2).max()))
                moved = np.flatnonzero(np.abs(t1 - nominal) > 1e-12)
                if not (len(moved) == 1 and moved[0] == i):
                    # When the nominal pose sits on a URDF joint limit / target bound, the one-hot in that
                    # direction is legitimately clamped away (e.g. the standing knee at 0 is the straight-leg
                    # limit): not an error. Moving a different joint is an error.
                    if len(moved) != 0:
                        moved_ok = False
                    else:
                        clamp_note = False
                # chain 3: three values of raw_now (normal / off by +2π / off by -4π)
                for raw in (0.3, 0.3 + 2 * np.pi, 0.3 - 4 * np.pi):
                    rt = bridge_roundtrip(rows, io.names[i], t1[i], raw)
                    worst = max(worst, abs(rt - t1[i]))
                digest.update(f"{tag}|{i}|{s:+.1f}|" .encode())
                digest.update(np.round(t1, 9).tobytes())
        check(f"{tag}: chain 1 == chain 2 == chain 3 (24 one-hot × 3 raw)", worst < 1e-9,
              f"max|Δ| {worst:.2e}")
        check(f"{tag}: a one-hot moves only its own joint", moved_ok,
              "" if clamp_note else "(some are legitimately clamped at a joint limit, e.g. the standing knee at 0)")
    import subprocess
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                            capture_output=True, text=True).stdout.strip()
    # The digest is pure float64 math, bit-deterministic across IEEE 754 machines, so two machines that
    # disagree almost always have different input files. A hash of the input files and a dirty flag are
    # printed next to the revision, so that "different math" and "different files" can be told apart at once.
    # Untracked files cannot change the contract inputs, hence --untracked-files=no.
    dirty = subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"],
                           cwd=ROOT, capture_output=True, text=True).stdout.strip()
    src = hashlib.sha256()
    for p in ("biped_Laika/biped_Laika.yaml", "tools/policy_io.py", "biped_Laika/isaac_values.py",
              "tools/contract_check.py"):
        src.update(open(os.path.join(ROOT, p), "rb").read())
    print(f"\n[contract] one-hot digest = {digest.hexdigest()[:12]}"
          f"  (repo {commit}{'+dirty' if dirty else ''}, input files {src.hexdigest()[:12]})")
    print("         run this command on each machine you use (training workstation, robot computer, ...): identical digests = bit-identical math")
    print("         different digests and different 'input files' hashes -> the files differ, not the math: sync the files first")


def run_onehot_mujoco(profile="walk"):
    """Physical check in MuJoCo: feed each one-hot target to the simulated plant and verify that the joint
    that physically moves is joint i, and that it turns in the commanded direction. The math chains cannot
    prove this: the axis directions are defined by the MJCF, so a flipped axis or a wrong mapping in the
    URDF -> MJCF conversion only shows up in a physical test. (The same physical check on the Isaac side is
    up to your training environment.)

    Method: base fixed and gravity off, so the PD steady state is the target itself (what remains is the
    static-friction band tau_c / kp, about 0.01 rad or less). For every one-hot, check which DOF has the largest
    |Δq|, its sign, the value it settles on, and that all other joints stay still."""
    import mujoco
    from tools.policy_io import PolicyIO
    sys.path.insert(0, ROOT)
    import gains
    cfg = yaml.safe_load(open(os.path.join(ROOT, "biped_Laika/biped_Laika.yaml")))
    io = PolicyIO(cfg, profile)
    g = gains.profile("rl_default")
    m = mujoco.MjModel.from_xml_path(os.path.join(ROOT, "biped_Laika", "biped_Laika.xml"))
    m.opt.gravity[:] = 0.0
    d = mujoco.MjData(m)
    key = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_KEY, "standing")
    jadr = np.array([m.jnt_qposadr[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, n)]
                     for n in io.names])
    vadr = np.array([m.jnt_dofadr[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, n)]
                     for n in io.names])
    kp = np.array([g[n]["kp"] for n in io.names])
    kd = np.array([g[n]["kd"] for n in io.names])
    tmax = np.array([g[n]["tau_max"] for n in io.names])
    # Threshold for "settled" / "still" = each joint's static-friction band: the PD loop legitimately stops
    # where |kp * err| <= tau_c (e.g. RS00: tau_c / kp = 0.13 / 12 ≈ 0.011 rad). Margin 2x + 1 mrad: MuJoCo
    # regularises friction in its constraint solver, which leaves about 2 mrad beyond the ideal band. The
    # purpose of this check is index / direction / magnitude, not measuring friction.
    stic = m.dof_frictionloss[vadr] / kp * 2.0 + 1e-3
    steps = int(0.8 / m.opt.timestep)
    idx_ok = sign_ok = conv_ok = still_ok = True
    worst_conv = worst_still = 0.0
    for i in range(12):
        for s in (+0.1, -0.1):
            a = np.zeros(12)
            a[i] = s
            target = io.action_to_target(a)
            if abs(target[i] - io.default[i]) < 0.01:
                continue                          # clamped at a joint limit: nothing to check physically (--onehot notes it)
            mujoco.mj_resetDataKeyframe(m, d, key)
            d.qpos[jadr] = io.default
            d.qvel[:] = 0.0
            base = d.qpos[:7].copy()
            for _ in range(steps):
                d.qpos[:7] = base                # hold the base fixed (rigidly suspended)
                d.qvel[:6] = 0.0
                q, qd = d.qpos[jadr], d.qvel[vadr]
                tau = np.clip(kp * (target - q) - kd * qd, -tmax, tmax)
                d.qfrc_applied[:] = 0.0
                d.qfrc_applied[vadr] = tau
                mujoco.mj_step(m, d)
            dq = d.qpos[jadr] - io.default
            moved = int(np.argmax(np.abs(dq)))
            idx_ok &= moved == i
            sign_ok &= np.sign(dq[i]) == np.sign(target[i] - io.default[i])
            conv = abs(dq[i] - (target[i] - io.default[i]))
            worst_conv = max(worst_conv, conv - stic[i])
            conv_ok &= conv < stic[i]
            others = float(np.max(np.abs(np.delete(dq, i)) - np.delete(stic, i)))
            worst_still = max(worst_still, others)
            still_ok &= others < 0.0
    check(f"MuJoCo physics: a one-hot moves its own DOF (index)", idx_ok)
    check(f"MuJoCo physics: the joint turns in the commanded direction (sign)", sign_ok)
    check(f"MuJoCo physics: the joint settles on the target (residual within its static-friction band)", conv_ok,
          f"max excess over the band {worst_conv:+.4f} rad")
    check(f"MuJoCo physics: all other joints stay still (within their static-friction bands)", still_ok,
          f"max excess over the band {worst_still:+.4f} rad")
    print(f"\n[contract] MuJoCo physical check done (profile={profile}, gravity off / base fixed). "
          f"The same physical check on the Isaac side is up to your training environment.")


def run_replay(dump_path, policy_path):
    import onnxruntime as ort
    from tools.onnx_manifest import _sha16, read
    z = np.load(dump_path, allow_pickle=False)
    obs, out_ref = z["obs"], z["out"]
    K, dim = obs.shape
    print(f"[contract] replaying {os.path.basename(dump_path)}: {K} frames × {dim} observation values, "
          f"recorded with policy={z['policy']} profile={z['profile']} (sha {z['model_sha16']})")
    sha = _sha16(policy_path)
    check("the model file is the one used for the recording (sha16)", sha == str(z["model_sha16"]),
          f"{sha} vs {z['model_sha16']}")
    man = read(policy_path)
    if man:
        check("observation size matches the manifest", man["contract"]["obs_dim"] == dim,
              f"{man['contract']['obs_dim']} vs {dim}")
    sess = ort.InferenceSession(policy_path, providers=["CPUExecutionProvider"])
    iname = sess.get_inputs()[0].name
    out_here = np.stack([
        np.asarray(sess.run(None, {iname: obs[k].reshape(1, -1)})[0]).reshape(-1)[:out_ref.shape[1]]
        for k in range(K)]).astype(np.float32)
    d = np.abs(out_here - out_ref)
    bitwise = int((d == 0).all(axis=1).sum())
    print(f"  max|Δ| = {d.max():.3e}   bit-identical frames {bitwise}/{K}")
    check("outputs match element by element (≤1e-6; bit-identical expected on the same machine)", float(d.max()) <= 1e-6,
          f"max|Δ| {d.max():.3e}")
    if bitwise < K:
        print("  note: not bit-identical but within 1e-6 = different floating-point kernels across CPU architectures (NEON vs AVX): accepted")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--onehot", action="store_true", help="check the action -> joint target mapping of every profile (pure math, no simulator)")
    ap.add_argument("--onehot-mujoco", action="store_true",
                    help="physical check in MuJoCo: one-hot targets on the simulated plant; verifies joint index / direction / settling")
    ap.add_argument("--replay", metavar="DUMP_NPZ", help="replay observations recorded on the robot with deploy_policy.py --dump-frames; needs --policy")
    ap.add_argument("--policy", metavar="ONNX", help="the ONNX file used when the dump was recorded (for --replay)")
    args = ap.parse_args()
    if args.onehot:
        run_onehot()
    elif args.onehot_mujoco:
        run_onehot_mujoco()
    elif args.replay:
        assert args.policy, "--replay needs --policy with the ONNX that the recording was made with"
        run_replay(args.replay, args.policy)
    else:
        ap.print_help()
        return
    print()
    print("ALL PASS" if not FAIL else f"FAILED: {FAIL}")
    sys.exit(1 if FAIL else 0)


if __name__ == "__main__":
    main()
